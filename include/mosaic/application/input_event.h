// Screen and window coordinates:
//
// (0, 0)┌─ Main Display ───────────────────────────────────┐
//       │                                                  │
//       │  window.position                                 │
//       │       ->┌ Window ────────┐                       │
//       │         │(0, 0)          │                       │
//       │         │                │                       │
//       │         │                │                       │
//       │         │     window.size│                       │
//       │         └────────────────┘                       │
//       │                          ^                       │
//       │                   window.position + window.size  │
//       │                                                  │
//       │                                                  │
//       └──────────────────────────────────────────────────┘ Display size

// Input Event Class Hierarchy:
//
//     InputEvent
//     ├── MouseEvent
//     │   ├── MouseDownEvent
//     │   │   ├── LeftMouseDownEvent
//     │   │   ├── RightMouseDownEvent
//     │   │   └── OtherMouseDownEvent
//     │   ├── MouseUpEvent
//     │   │   ├── LeftMouseUpEvent
//     │   │   ├── RightMouseUpEvent
//     │   │   └── OtherMouseUpEvent
//     │   ├── MouseDragEvent
//     │   │   ├── LeftMouseDragEvent
//     │   │   ├── RightMouseDragEvent
//     │   │   └── OtherMouseDragEvent
//     │   ├── MouseMoveEvent
//     │   ├── ScrollEvent
//     │   └── MagnificationEvent
//     ├── KeyEvent
//     │   ├── KeyDownEvent
//     │   └── KeyUpEvent
//     └── ModifiersChangedEvent
//

